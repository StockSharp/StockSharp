	private async IAsyncEnumerable<Message> ReadOrderCancelRejectAsync(IFixReader reader, [EnumeratorCancellation]CancellationToken cancellationToken)
	{
		string clOrdId = null;
		string orderId = null;
		var sendingTime = default(DateTime);
		DateTime? transactTime = null;
		string text = null;

		var isOk = await reader.ReadMessageAsync(async (tag, ct) =>
		{
			switch (tag)
			{
				case FixTags.ClOrdID:
					clOrdId = await reader.ReadStringAsync(ct);
					return true;
				case FixTags.OrderID:
					orderId = await reader.ReadStringAsync(ct);
					return true;
				case FixTags.SendingTime:
					sendingTime = await reader.ReadUtcAsync(TimeStampParser, ct);
					return true;
				case FixTags.TransactTime:
					transactTime = await reader.ReadUtcAsync(TimeStampParser, ct);
					return true;
				case FixTags.Text:
					text = await reader.ReadStringAsync(ct);
					return true;
				default:
					return false;
			}
		}, cancellationToken);

		if (!isOk)
			yield break;

		var msg = new ExecutionMessage
		{
			OriginalTransactionId = clOrdId.To<long>(),
			ServerTime = transactTime ?? sendingTime,
			DataTypeEx = DataType.Transactions,
			OrderState = OrderStates.Failed,
			Error = new InvalidOperationException(LocalizedStrings.ErrorCancellingOrder.Put(orderId, text)),
			HasOrderInfo = true,
		};

		if (orderId != null)
		{
			if (long.TryParse(orderId, out var orderNumId))
				msg.OrderId = orderNumId;
			else
				msg.OrderStringId = GetOrderStringId(orderId);
		}

		yield return msg;
	}

	private static async IAsyncEnumerable<Message> ReadRequestForPositionAckAsync(IFixReader reader, [EnumeratorCancellation]CancellationToken cancellationToken)
	{
		string account = null;
		PosReqResult? posReqResult = null;
		PosReqStatus? posReqStatus = null;
		string text = null;

		var isOk = await reader.ReadMessageAsync(async (tag, ct) =>
		{
			switch (tag)
			{
				case FixTags.Account:
					account = await reader.ReadStringAsync(ct);
					return true;
				case FixTags.PosReqResult:
					posReqResult = (PosReqResult)await reader.ReadIntAsync(ct);
					return true;
				case FixTags.PosReqStatus:
					posReqStatus = (PosReqStatus)await reader.ReadIntAsync(ct);
					return true;
				case FixTags.Text:
					text = await reader.ReadStringAsync(ct);
					return true;
				default:
					return false;
			}
		}, cancellationToken);

		if (!isOk)
			yield break;

		if (posReqResult != null && posReqResult != 0 && (posReqStatus == PosReqStatus.Rejected || (posReqStatus == null && posReqResult != PosReqResult.ValidRequest)))
			yield return LocalizedStrings.RecvPosRejected2.Put(account, posReqResult, text).ToErrorMessage();
	}
