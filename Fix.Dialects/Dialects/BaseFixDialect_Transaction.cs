		await Task.Yield();
		yield return message;
	}

	/// <summary>
	/// Get order type.
	/// </summary>
	/// <param name="report">Execution report.</param>
	/// <param name="condition">Base order condition (for example, for stop order algo orders).</param>
	/// <returns>Order type.</returns>
	protected virtual OrderTypes GetOrderType(ExecutionReport report, out OrderCondition condition)
	{
		if (report is null)
			throw new ArgumentNullException(nameof(report));

		condition = null;

		switch (report.OrdType)
		{
			case OrdType.Limit:
				return OrderTypes.Limit;
			case OrdType.Market:
				return OrderTypes.Market;
			default:
				condition = new FixOrderCondition { StopLoss = report.StopPx, TakeProfit = report.TakeProfit };
				return OrderTypes.Conditional;
		}
	}

	/// <summary>
	/// Process <see cref="ExecutionReport.Parties"/>.
	/// </summary>
	/// <param name="report">Execution report.</param>
	protected virtual void ProcessParties(ExecutionReport report)
	{
		report.ClientId ??= report.Parties.FirstOrDefault(p => p.PartyRole == PartyRole.ClientId)?.PartyId;

		report.ExecBroker ??= report.Parties.FirstOrDefault(p => p.PartyRole == PartyRole.ExecutingFirm)?.PartyId;
	}

	/// <summary>
	/// Get <see cref="ExecutionMessage.OrderStringId"/>.
	/// </summary>
	/// <param name="orderId"><see cref="ExecutionMessage.OrderStringId"/> value.</param>
	/// <returns><see cref="ExecutionMessage.OrderStringId"/> value.</returns>
	protected virtual string GetOrderStringId(string orderId)
	{
		if (orderId.IsEmpty())
			return orderId;

		return orderId.EqualsIgnoreCase("none") ? null : orderId;
	}

	/// <summary>
	/// Get execution time.
	/// </summary>
	protected virtual DateTime GetExecutionTime(ExecutionReport report)
		=> report.TransactTime ?? report.TrdRegTimestamp ?? report.TradeDate ?? report.OrigSendingTime ?? report.SendingTime;

	/// <summary>
	/// Process <see cref="ExecutionReport"/> instance.
	/// </summary>
	/// <param name="report"><see cref="ExecutionReport"/> instance.</param>
	/// <param name="processExecMsg">Post handle an <see cref="ExecutionMessage"/> instance.</param>
	/// <param name="cancellationToken"><see cref="CancellationToken"/></param>
	protected virtual async IAsyncEnumerable<Message> ProcessExecutionReportAsync(ExecutionReport report, Func<ExecutionReport, ExecutionMessage, CancellationToken, IAsyncEnumerable<ExecutionMessage>> processExecMsg, [EnumeratorCancellation]CancellationToken cancellationToken)
	{
		if (report is null)
			throw new ArgumentNullException(nameof(report));

		if (processExecMsg is null)
			throw new ArgumentNullException(nameof(processExecMsg));

		// TODO OrderLog

		//long? originalTransactionId = null;

		//if (long.TryParse(report.OrigClOrdId, out temp))
		//	originalTransactionId = temp;

		//long? transactionId = null;

		//if (long.TryParse(report.ClOrdId, out temp))
		//	transactionId = temp;

		long? clOrdId = null;

		if (!report.ClOrdId.IsEmpty())
		{
			if (long.TryParse(report.ClOrdId, out var c))
				clOrdId = c;
			else if (SupportUnknownExecutions)
			{
				if (_clOrdIds.TryGetKey(report.ClOrdId, out c))
					clOrdId = c;
				else
				{
					clOrdId = _transactionIdGenerator.GetNextId();
					_clOrdIds[clOrdId.Value] = report.ClOrdId;
				}
			}
		}

		var isOrderStatus = false;
		long? originalTransactionId = null;

		if (long.TryParse(report.OrdStatusReqId, out var temp))
		{
			originalTransactionId = temp;
			isOrderStatus = true;
		}
		else if (long.TryParse(report.MassStatusReqId, out temp))
		{
			originalTransactionId = temp;
			isOrderStatus = true;
		}
		else if (report.PossDupFlag == true) // ResendRequest reports
		{
			if (long.TryParse(report.OrigClOrdId, out temp))
			{
				originalTransactionId = temp;

				if (report.ExecType == ExecType.Canceled)
				{
					clOrdId = originalTransactionId;
					originalTransactionId = LastResendRequest;
					isOrderStatus = true;
				}
			}
			else
			{
				if (report.ExecType == ExecType.Trade)
				{
					if (long.TryParse(report.ClOrdId, out temp))
						originalTransactionId = temp;
					else if (long.TryParse(report.OrigClOrdId, out temp))
						originalTransactionId = temp;
				}
				else
				{
					originalTransactionId = LastResendRequest;
					isOrderStatus = true;
				}
			}
		}
		else if (clOrdId != null)
			originalTransactionId = clOrdId.Value;
		else if (long.TryParse(report.OrigClOrdId, out temp))
			originalTransactionId = temp;

		if (report.Parties != null)
			ProcessParties(report);

		if (report.ClientId.IsEmpty())
			report.ClientId = ClientCode;

		var time = GetExecutionTime(report);

		async IAsyncEnumerable<ExecutionMessage> CreateOrderMsg()
		{
			//if (originalTransactionId == null)
			//	originalTransactionId = transactionId;

			//if (originalTransactionId == null && ignoreIfTransIdNull)
			//	return null;

			// если сообщение не содержит объем или баланс, значит нет информации по заявке
			//if (orderQty == null && leavesQty == null)
			//	return null;

			if (report.OrderQty == 0)
				report.OrderQty = null;

			if (report.OrdStatus == OrdStatus.Canceled)
			{
				if (report.LeavesQty == 0)
					report.LeavesQty = null;
			}

			var msg = new ExecutionMessage
			{
				SecurityId = new SecurityId
				{
					SecurityCode = report.Symbol,
					BoardCode = GetBoardCode(report.ExDestination, report.SecurityExchange, report.TradingSessionId),
				},
				//TransactionId = transactionId ?? 0,
				OriginalTransactionId = originalTransactionId ?? 0,
				OrderPrice = report.Price ?? 0,
				OrderVolume = report.OrderQty,
				PortfolioName = GetAccountId(report.Account),
				Side = report.Side?.FromFixSide() ?? default,
				ServerTime = time,
				Balance = (report.OrderQty != null && report.CumQty != null) ? (report.OrderQty - report.CumQty) : report.LeavesQty,
				OrderState = GetOrderState(report),
				DataTypeEx = DataType.Transactions,
				Commission = report.Commission,
				CommissionCurrency = report.CommissionCurrency,
				ClientCode = report.ClientId,
				BrokerCode = report.ExecBroker,
				TradePrice = report.LastPx?.DefaultAsNull(),
				TradeVolume = report.LastQty?.DefaultAsNull(),
				VisibleVolume = report.MaxFloor ?? report.DisplayQty,
				OrderStatus = report.ExtendedOrderStatus,
				TradeStatus = report.ExtendedTradeStatus,
				MarginMode = report.CashMargin?.ToMarginMode(),
				AveragePrice = report.AvgPx?.DefaultAsNull(),
				Yield = report.Yield,
				MinVolume = report.MinQty,
				PositionEffect = report.PositionEffect.ToPositionEffect(),
				Initiator = report.AggressorIndicator,
				IsManual = report.ManualOrderIndicator,
				SeqNum = report.MsgSeqNum,
				UserOrderId = report.SecondaryOrderId,
				StrategyId = report.StrategyTypeId,
				Leverage = report.Leverage,
				MarketPrice = report.MarketPrice,
			};

			if (msg.Balance != null || msg.OrderState != null || msg.OrderVolume != null || report.Price != null)
				msg.HasOrderInfo = true;

			if (report.OrdType != null)
			{
				msg.OrderType = GetOrderType(report, out var condition);
				msg.Condition = condition;
				msg.HasOrderInfo = true;
			}

			if (report.OrderId != null)
			{
				if (long.TryParse(report.OrderId, out var orderNumId))
					msg.OrderId = orderNumId;
				else
					msg.OrderStringId = GetOrderStringId(report.OrderId);

				//msg.HasOrderInfo = true;
			}

			if (Native.Extensions.IsMarketMaker(report.OrderCapacity, report.OrderRestrictions))
				msg.IsMarketMaker = true;

			if (isOrderStatus)
				msg.TransactionId = clOrdId ?? 0;

			//if (_orderStatusTransactions.Contains(msg.OriginalTransactionId))

			await foreach (var r in processExecMsg(report, msg, cancellationToken))
			{
				if (r.OrderState == OrderStates.Failed)
				{
					r.Error = new InvalidOperationException(report.Text);
					r.HasOrderInfo = true;
				}
				else
					r.Comment = report.Text;

				r.HasOrderInfo |= ApplyTimeInForce(report, msg);

				yield return r;
			}
		}

		static Sides? LastLiquidityIndToSide(Sides? side, int? value)
		{
			// Which side initiated the trade is read off the order's own side, so a report that
			// states none says nothing about the initiator either.
			if (side is not Sides orderSide)
				return null;

			return value switch
			{
				null => null,
				1 => orderSide.Invert(),
				2 or 3 => orderSide,
				_ => throw new ArgumentOutOfRangeException(nameof(value), value, LocalizedStrings.InvalidValue),
			};
		}

		switch (report.ExecType)
		{
			case ExecType.PendingNew:
			case ExecType.PendingReplace:
			case ExecType.New:
			case ExecType.OrderStatus:
			case ExecType.Canceled:
			case ExecType.Fill:
			case ExecType.PartialFill:
			case ExecType.Replaced:
			case ExecType.Calculated:
			{
				if (report.ExecType == ExecType.Canceled && report.LeavesQty == 0)
					report.LeavesQty = null;

				await foreach (var msg in CreateOrderMsg())
				{
					//if (msg == null)
					//	break;

					if (report.ExecType == ExecType.Fill || report.ExecType == ExecType.PartialFill)
					{
						msg.OriginSide ??= LastLiquidityIndToSide(msg.Side, report.LastLiquidityInd);

						if (msg.TradeId == null && msg.TradeStringId.IsEmpty() && report.ExecId != null)
						{
							if (long.TryParse(report.ExecId, out var tradeNumId))
								msg.TradeId = tradeNumId;
							else
								msg.TradeStringId = report.ExecId;
						}
					}

					yield return msg;
				}
				
				break;
			}
			case ExecType.Rejected:
			{
				//if (originalTransactionId == null)
				//	originalTransactionId = transactionId;

				//if (originalTransactionId != null)
				//{
				if (originalTransactionId == null && SupportUnknownExecutions)
				{
					if (_clOrdIds.TryGetKey(report.OrigClOrdId, out temp))
						originalTransactionId = temp;
				}

				var msg = new ExecutionMessage
				{
					//SecurityId = new SecurityId
					//{
					//	SecurityCode = symbol,
					//	BoardCode = session.GetBoardCode(securityExchange, tradingSessionId),
					//},
					ServerTime = report.SendingTime,
					DataTypeEx = DataType.Transactions,
					OrderState = OrderStates.Failed,
					Error = new InvalidOperationException(report.Text),
					Commission = report.Commission,
					CommissionCurrency = report.CommissionCurrency,
					ClientCode = report.ClientId,
					HasOrderInfo = true,
					SeqNum = report.MsgSeqNum,
					UserOrderId = report.SecondaryOrderId,
					StrategyId = report.StrategyTypeId,
					Leverage = report.Leverage,
					MarketPrice = report.MarketPrice,
				};

				if (report.PossDupFlag == true)
				{
					msg.TransactionId = report.ClOrdId.TryToLong() ?? 0;
				}

				msg.OriginalTransactionId = originalTransactionId ?? 0;

				if (long.TryParse(report.OrderId, out var orderIdNum))
					msg.OrderId = orderIdNum;
				else
					msg.OrderStringId = GetOrderStringId(report.OrderId);

				await foreach (var r in processExecMsg(report, msg, cancellationToken))
					yield return r;

				break;
				//}
			}
			case ExecType.Trade:
			{
				await foreach (var msg in CreateOrderMsg())
				{
					msg.OriginSide ??= LastLiquidityIndToSide(msg.Side, report.LastLiquidityInd);

					if (msg.TradeId == null && msg.TradeStringId.IsEmpty() && report.ExecId != null)
					{
						if (long.TryParse(report.ExecId, out var tradeNumId))
							msg.TradeId = tradeNumId;
						else
							msg.TradeStringId = report.ExecId;
					}

					yield return msg;
				}
				
				break;
			}
			case ExecType.PendingCancel:
				break;
			default:
				throw new InvalidOperationException(LocalizedStrings.UnknownType.Put(report.ExecType));
		}
	}

	/// <summary>
	/// Apply time in force.
	/// </summary>
	/// <param name="report"></param>
	/// <param name="msg"></param>
	/// <param name="throwInvalid"></param>
	protected virtual bool ApplyTimeInForce(ExecutionReport report, ExecutionMessage msg, bool throwInvalid = true)
	{
		switch (report.TimeInForce)
		{
			case FixTimeInForce.GoodTillCancel:
				msg.TimeInForce = Messages.TimeInForce.PutInQueue;
				return true;
			case FixTimeInForce.Day:
				msg.TimeInForce = Messages.TimeInForce.PutInQueue;
				msg.ExpiryDate = Messages.Extensions.Today;
				return true;
			case FixTimeInForce.GoodTillDate:
				msg.TimeInForce = Messages.TimeInForce.PutInQueue;
				msg.ExpiryDate = report.ExpireTime ?? report.ExpireDate;
				return true;
			case FixTimeInForce.FillOrKill:
				msg.TimeInForce = Messages.TimeInForce.MatchOrCancel;
				return true;
			case FixTimeInForce.ImmediateOrCancel:
				msg.TimeInForce = Messages.TimeInForce.CancelBalance;
				return true;
			case null:
				return false;
			default:
				if(throwInvalid)
					throw new ArgumentOutOfRangeException(nameof(report), report.TimeInForce, LocalizedStrings.InvalidValue);

				return false;
		}
	}

